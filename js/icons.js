/** Build an inline SVG string for an icon name. */
function icon(name, cls) {
  const paths = ICON_PATHS[name];
  if (!paths) return '';
  return '<svg class="' + (cls || 'ic') + '" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" ' +
    'stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' +
    paths + '</svg>';
}

/** Replace every <i data-icon="..."> placeholder inside `root` with its SVG. */
function renderIcons(root) {
  (root || document).querySelectorAll('i[data-icon]').forEach(function (el) {
    const svg = icon(el.dataset.icon, el.className || 'ic');
    if (svg) el.outerHTML = svg;
  });
}
